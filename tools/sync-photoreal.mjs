#!/usr/bin/env node
/**
 * Propagate shared/photoreal.js into every game.
 *
 * The games are meant to stay self-contained — one folder, open it and it runs —
 * so none of them import across folder boundaries at runtime. city-storm is
 * already a multi-file module app and just gets a copy of the file; the two
 * single-file games get the source spliced into their HTML between the marker
 * comments, with `export ` stripped since it is not a module boundary there.
 *
 * Run from the repo root:  node tools/sync-photoreal.mjs [--check]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'shared', 'photoreal.js');
const BEGIN = '/* === BEGIN photoreal kit (generated by tools/sync-photoreal.mjs) === */';
const END = '/* === END photoreal kit === */';

const check = process.argv.includes('--check');
const source = fs.readFileSync(SRC, 'utf8');

/** Module copies keep the file verbatim. */
const COPIES = [path.join(ROOT, 'city-storm', 'photoreal.js')];

/** Inline targets get the exports stripped and the body spliced in. */
// tank-battle-android is deliberately absent: it bundles its own trimmed copy of
// Three.js that has no SMAAPass, and the post chain needs gating behind the
// touch build's quality presets before it is safe on a phone. Until that port
// happens it stays on the older renderer rather than being half-synced.
const INLINE = [
  path.join(ROOT, 'tank-battle', 'index.html'),
  path.join(ROOT, 'falcon-strike', 'index.html'),
];

// Inlined copies are wrapped in an IIFE that exposes only the exported names.
// Splicing the module body straight into a game's script would drop internals
// like `fbm` and `texture` into its scope — and both single-file games already
// define an `fbm` of their own, which is a duplicate-declaration SyntaxError.
const exported = [...source.matchAll(/^export (?:function|const) ([A-Za-z0-9_$]+)/gm)].map((m) => m[1]);
if (!exported.length) { console.error('no exports found in shared/photoreal.js'); process.exit(1); }
const inlineBody = [
  BEGIN,
  'const PR = (() => {',
  source.replace(/^export /gm, ''),
  `return { ${exported.join(', ')} };`,
  '})();',
  END,
].join('\n');

let stale = 0;
const write = (file, next) => {
  const prev = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (prev === next) return console.log(`  up to date  ${path.relative(ROOT, file)}`);
  stale++;
  if (check) return console.log(`  STALE       ${path.relative(ROOT, file)}`);
  fs.writeFileSync(file, next);
  console.log(`  written     ${path.relative(ROOT, file)}`);
};

for (const file of COPIES) {
  const header = `/* GENERATED — do not edit. Source: shared/photoreal.js (tools/sync-photoreal.mjs). */\n`;
  write(file, header + source);
}

for (const file of INLINE) {
  if (!fs.existsSync(file)) { console.log(`  skipped     ${path.relative(ROOT, file)} (absent)`); continue; }
  const html = fs.readFileSync(file, 'utf8');
  const a = html.indexOf(BEGIN), b = html.indexOf(END);
  if (a === -1 || b === -1) {
    console.log(`  no markers  ${path.relative(ROOT, file)} — add ${BEGIN} / ${END} inside the module script`);
    stale++;
    continue;
  }
  write(file, html.slice(0, a) + inlineBody + html.slice(b + END.length));
}

if (check && stale) {
  console.error(`\n${stale} target(s) out of date — run: node tools/sync-photoreal.mjs`);
  process.exit(1);
}
console.log(stale ? '\nsynced' : '\nall targets already current');
